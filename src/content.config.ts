import { defineCollection } from 'astro:content';
import { glob } from 'astro/loaders';
import { z } from 'astro/zod';
import { CONTENT_TYPES } from './config/navigation';
import { site } from './config/site';
import { createSourcePolicy, isAllowedArticleSource } from './lib/source-policy';
import { ARTICLE_TEMPLATE } from './config/article-template';

const ARTICLE_SOURCE_POLICY = createSourcePolicy(
  site.social.official,
  site.social.reddit,
  site.trustedStorePages,
  site.trustedMaterialPages,
);

/**
 * Wiki content collection.
 *
 * Articles live at src/content/wiki/<locale>/<contentType>/<slug>.mdx
 * The `id` generated by the glob loader is the path relative to base, without extension,
 * e.g. "en/bosses/emberfang".
 *
 * Frontmatter is validated at build time by the Zod schema below. A missing or
 * malformed field fails the build immediately.
 *
 * The first local image in the MDX body is the article cover. A body image is
 * mandatory; this prevents thin articles from silently receiving a generic or
 * unrelated cover.
 */
const wiki = defineCollection({
  loader: glob({ pattern: '**/*.mdx', base: './src/content/wiki' }),
  schema: () =>
    z.object({
      title: z.string().max(80),
      template: z.literal(ARTICLE_TEMPLATE.id).default(ARTICLE_TEMPLATE.id),
      description: z.string().min(40).max(165),
      /**
       * Hard gate: the category MUST be a NAVIGATION_CONFIG key. A typo'd
       * category would otherwise build a soft-404 page that sitemap/RSS/
       * llms.txt still publish — the enum fails the build instead.
       */
      category: z.enum(CONTENT_TYPES as [string, ...string[]]),
      date: z.coerce.date(),
      lastModified: z.coerce.date().optional(),
      tags: z.array(z.string()).default([]),
      /** Search-intent terms used for the article keywords meta tag and content planning. */
      keywords: z.array(z.string().min(1).max(80)).max(8).default([]),
      noindex: z.boolean().default(false),
      /**
       * Draft articles: visible in `pnpm dev`, excluded from the production
       * build (pages, lists, recent, related, hreflang, sitemap).
       */
      draft: z.boolean().default(false),
      /**
       * Game version this article applies to (e.g. "v2.5"). Rendered as a
       * badge on the article header — a freshness/E-E-A-T signal for
       * fast-patching games. Optional.
       */
      gameVersion: z.string().max(20).optional(),
      /**
       * Quick-answer summary shown before the article body (AI Overviews /
       * featured snippet). Authoring rule: 40–60 words. English at that
       * length runs ~250–350 chars, so the cap is 400 — the old 200-char cap
       * contradicted the word rule (40 English words ≈ 230+ chars) and
       * silently forced every compliant summary underweight.
       */
      summary: z.string().min(1).max(400),
      /** Article author name (E-E-A-T signal). Falls back to site.defaultAuthor. */
      author: z.string().optional(),
      /**
       * Optional structured boss stats — rendered as a scannable data card
       * (BossStatCard) above the article body. Values are strings so authors
       * can express nuance ("4200 (Phase 2: 6300)").
       */
      boss: z
        .object({
          hp: z.string(),
          weakness: z.string(),
          resistant: z.string(),
          location: z.string(),
          recommendedLevel: z.string().optional(),
        })
        .optional(),
      /**
       * Optional YouTube IDs for videos intentionally embedded in the MDX
       * body with <Video>. Ordinary video references belong in `sources`.
       * 11-char IDs, not full URLs.
       */
      videos: z.array(z.string()).optional(),
      /**
       * Structured redeem codes (codes pages). Rendered as a CodesTable
       * above the article body: Active section (CodeBlock, one-click copy)
       * + Expired section (table, long-tail SEO for "is X still working").
       * `status` drives the split; `expiryDate`/`source` are freshness and
       * E-E-A-T signals. Body stays for prose (how to redeem, reward notes).
       */
      codes: z
        .array(
          z.object({
            code: z.string().min(1),
            reward: z.string().optional(),
            status: z.enum(['active', 'expired']).default('active'),
            expiryDate: z.string().max(40).optional(),
            source: z.string().optional(),
          }),
        )
        .optional(),
      /**
       * Per-article FAQ (any page type). Rendered as a visible <details>
       * block near the end of the page AND as FAQPage JSON-LD — markup must
       * mirror visible content (Google rich-results policy). Merged with the
       * codes FAQ into a single FAQPage entity (one per page).
       */
      faq: z
        .array(
          z.object({
            question: z.string().min(1),
            answer: z.string().min(1),
          }),
        )
        .optional(),
      /** Optional article-level decision helper rendered before the MDX body. */
      decisionFilter: z
        .object({
          title: z.string().min(1).max(120),
          prompt: z.string().min(1).max(160).optional(),
          emptyLabel: z.string().min(1).max(200).optional(),
          items: z
            .array(
              z.object({
                label: z.string().min(1).max(120),
                value: z.string().min(1).max(80),
                answer: z.string().min(1).max(240),
                detail: z.string().min(1).max(600),
              }),
            )
            .min(2)
            .max(8),
        })
        .optional(),
      /** Optional article-level checklist with selectable plans and copy support. */
      taskPlanner: z
        .object({
          title: z.string().min(1).max(120),
          prompt: z.string().min(1).max(200).optional(),
          options: z
            .array(
              z.object({
                label: z.string().min(1).max(120),
                value: z.string().min(1).max(80),
                answer: z.string().min(1).max(300),
                steps: z.array(z.string().min(1).max(300)).min(1).max(12),
                note: z.string().max(300).optional(),
              }),
            )
            .min(2)
            .max(6),
        })
        .optional(),
      /** Optional visual article diagnostic. */
      articleTool: z
        .discriminatedUnion('type', [
          z.object({
            type: z.literal('field-note'),
            eyebrow: z.string().min(1).max(80),
            title: z.string().min(1).max(120),
            body: z.string().min(1).max(600),
            icon: z.string().max(80).optional(),
            chips: z.array(z.string().min(1).max(80)).max(5).optional(),
            image: z.string().max(500).optional(),
            imageAlt: z.string().max(160).optional(),
            imageOrientation: z.enum(['landscape', 'portrait', 'square']).optional(),
          }),
          z.object({
            type: z.literal('readiness'),
            eyebrow: z.string().min(1).max(80),
            title: z.string().min(1).max(120),
            centerLabel: z.string().min(1).max(80),
            centerValue: z.string().max(40).optional(),
            summary: z.string().max(200).optional(),
            statusLabels: z
              .object({
                ready: z.string().min(1).max(40).optional(),
                check: z.string().min(1).max(40).optional(),
                missing: z.string().min(1).max(40).optional(),
              })
              .optional(),
            items: z
              .array(
                z.object({
                  label: z.string().min(1).max(120),
                  status: z.enum(['ready', 'check', 'missing']),
                  detail: z.string().min(1).max(300),
                }),
              )
              .min(3)
              .max(6),
          }),
        ])
        .optional(),
      /** Public evidence used by factual claims in the article body. */
      sources: z
        .array(
          z.object({
            title: z.string().min(1).max(240),
            url: z
              .string()
              .url()
              .refine((value) => /^https?:\/\//i.test(value), 'Source URL must use http or https')
              .refine(
                (value) => isAllowedArticleSource(value, ARTICLE_SOURCE_POLICY).allowed,
                'Source must be the configured official site, YouTube, Steam, or the configured game subreddit',
              ),
            publisher: z.string().max(120).optional(),
            publishedAt: z.string().max(40).optional(),
            note: z.string().max(300).optional(),
          }),
        )
        .default([]),
    }),
});

/**
 * Handbook collection — the in-site documentation center at /landing/docs
 * (+ /zh/landing/docs). Chapters live OUTSIDE src/content on purpose: the
 * markdown under docs/handbook/ is the single source of truth, browsable on
 * GitHub, and **survives `pnpm apply-template`** (the learning manual's SOPs
 * and AI prompts are directly useful to fork users) — only the landing ROUTES
 * are removed by the CLI.
 *
 * Files: docs/handbook/<locale>/<slug>.md → id "en/<slug>" / "zh/<slug>".
 * zh chapters MUST reuse the same ASCII slug as their en counterpart —
 * CJK filenames percent-encode in URLs, and 1:1 slug pairing makes the
 * en/zh parity test (tests/handbook.test.ts) trivial.
 *
 * Plain .md (not .mdx): handbooks are static prose + code blocks; they do not
 * use the wiki component vocabulary.
 */
const handbook = defineCollection({
  loader: glob({ pattern: '**/*.md', base: './docs/handbook' }),
  schema: z.object({
    title: z.string().max(80),
    description: z.string().min(40).max(165),
    /** Which manual the chapter belongs to (drives hub grouping + prev/next scope). */
    manual: z.enum(['learn', 'dev']),
    /** Position within the manual (1-based, unique per manual). */
    order: z.number().int(),
    icon: z.string().default('lucide:book-open'),
    /**
     * 40–60 word direct answer, rendered as the TL;DR card (AI Overviews
     * candidate). 480 chars ≈ 60-70 English words — zh lands well under,
     * en translations run longer per word.
     */
    tldr: z.string().max(480).optional(),
    /** Last content review — feeds the sitemap lastmod scan (astro.config.ts). */
    updated: z.coerce.date().optional(),
  }),
});

export const collections = { wiki, handbook };
