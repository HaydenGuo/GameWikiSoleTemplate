/** Generate the published canonical article paths trusted by Pages Functions. */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { collectPublishedArticleSlugs, type ContentSourceFile } from './lib/popular-manifest.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contentRoot = path.join(root, 'src', 'content', 'wiki');
const outputPath = path.join(root, 'src', 'generated', 'allowed-article-slugs.ts');

async function walk(directory: string): Promise<string[]> {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map(async (entry) => {
      const absolute = path.join(directory, entry.name);
      if (entry.isDirectory()) return walk(absolute);
      return entry.isFile() && entry.name.endsWith('.mdx') ? [absolute] : [];
    }),
  );
  return nested.flat();
}

const absoluteFiles = await walk(contentRoot);
const files: ContentSourceFile[] = await Promise.all(
  absoluteFiles.map(async (absolute) => ({
    relativePath: path.relative(contentRoot, absolute),
    source: await fs.readFile(absolute, 'utf8'),
  })),
);
const slugs = collectPublishedArticleSlugs(files);
const output = `/** Generated by scripts/generate-popular-slug-manifest.ts. Do not edit manually. */\nexport const allowedArticleSlugs = new Set<string>(${JSON.stringify(slugs, null, 2)});\n`;

await fs.mkdir(path.dirname(outputPath), { recursive: true });
await fs.writeFile(outputPath, output, 'utf8');
console.log(`Generated ${slugs.length} published article slugs at ${path.relative(root, outputPath)}.`);
